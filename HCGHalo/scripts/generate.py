def render_root_plist():
    return plistlib.dumps(ROOT_PLIST, fmt=plistlib.FMT_XML, sort_keys=True)


# --------------------------------------------------------------------------- main

def outputs():
    data = load_profiles()
    return {
        "src/HaloProfiles.generated.c": render_profiles_c(data).encode("utf-8"),
        "preferences/Resources/Root.plist": render_root_plist(),
    }


def main(argv):
    check = "--check" in argv
    stale = []
    for rel, content in outputs().items():
        path = os.path.join(ROOT, rel)
        current = open(path, "rb").read() if os.path.exists(path) else None
        if current == content:
            continue
        if check:
            stale.append(rel)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "wb") as f:
                f.write(content)
            print(f"wrote {rel}")
    if stale:
        print("stale generated files (run scripts/generate.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
